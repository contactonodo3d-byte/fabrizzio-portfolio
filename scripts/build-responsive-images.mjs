// Builds width-capped WebP variants for large portfolio images and writes
// src/image-variants.js. Originals stay in place and remain the img src.
import fs from 'node:fs';
import path from 'node:path';

const sharp = (await import('sharp').catch(() => {
  console.error('Regenerating variants needs sharp: npm install --no-save sharp');
  process.exit(1);
})).default;

const root = path.resolve(import.meta.dirname, '..');
const widths = [640, 960, 1280, 1600];
const media = JSON.parse(fs.readFileSync(path.join(root, 'src/selected-media.json'), 'utf8'));

const files = new Set();
for (const items of Object.values(media)) {
  if (items[0]?.url) files.add(items[0].url);
}
for (const extra of [
  '/images/selected/foody/foto-5.webp',
  '/images/selected/casa-albirroja/expo-nocturna.webp',
  '/images/selected/indufar-2026/001.webp',
  '/images/selected/gio-mobili/1.webp',
  '/images/selected/gio-mobili/2.webp',
  '/images/selected/black-sail/1.webp',
  '/images/work/skylinq.webp',
  '/images/work/social-media.webp',
  '/images/work/pitch-deck.webp',
  '/images/work/brand-identity.webp',
  '/images/work/archviz.webp',
  '/expo/assets/gestecner-op1-render.webp',
]) files.add(extra);

const variants = {};
let written = 0;
let saved = 0;

for (const url of [...files].sort()) {
  if (!url.endsWith('.webp')) continue;
  const source = path.join(root, 'public', url);
  if (!fs.existsSync(source)) {
    console.warn('missing', url);
    continue;
  }
  const originalBytes = fs.statSync(source).size;
  const meta = await sharp(source).metadata();
  if (!meta.width || meta.width < 800 || originalBytes < 40000) continue;
  const made = [];
  for (const width of widths) {
    if (meta.width < width * 1.2) continue;
    const destUrl = url.replace(/\.webp$/, `-${width}w.webp`);
    const dest = path.join(root, 'public', destUrl);
    const buf = await sharp(source)
      .resize({ width, withoutEnlargement: true })
      .webp({ quality: 82, effort: 4 })
      .toBuffer();
    if (buf.length >= originalBytes * 0.92) continue;
    fs.writeFileSync(dest, buf);
    made.push({ src: destUrl, width });
    written += 1;
    saved += originalBytes - buf.length;
  }
  if (made.length) variants[url] = made;
  console.log(`${url} ${meta.width}x${meta.height} ${originalBytes} -> ${made.map((item) => item.width).join(',') || 'skipped'}`);
}

const out = `// Generated by scripts/build-responsive-images.mjs. Do not edit by hand.\nexport const imageVariants = ${JSON.stringify(variants, null, 2)};\n`;
fs.writeFileSync(path.join(root, 'src/image-variants.js'), out);
console.log(`variants ${written}, sources ${Object.keys(variants).length}, bytes not duplicated ${saved}`);
